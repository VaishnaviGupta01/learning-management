-- Spaced-repetition schedule for a student/topic pair.
CREATE TABLE revision_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    topic_id BIGINT NOT NULL,
    stage VARCHAR(30) NOT NULL DEFAULT 'DAY_1' CHECK (stage IN ('DAY_1', 'DAY_3', 'DAY_7', 'DAY_14', 'DAY_30', 'MASTERED')),
    next_review_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    last_reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    review_count INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_revision_schedules UNIQUE (student_id, topic_id),
    CONSTRAINT fk_revision_schedules_student_id FOREIGN KEY (student_id) REFERENCES users (id),
    CONSTRAINT fk_revision_schedules_topic_id FOREIGN KEY (topic_id) REFERENCES topics (id)
);

CREATE INDEX idx_revision_schedules_student_id ON revision_schedules (student_id);
CREATE INDEX idx_revision_schedules_topic_id ON revision_schedules (topic_id);

-- Audit log of every AI request/response.
CREATE TABLE ai_interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    course_id BIGINT,
    topic_id BIGINT,
    type VARCHAR(30) NOT NULL CHECK (type IN ('CHAT', 'EXPLANATION', 'HINT', 'SUMMARY', 'QUESTION_GENERATION', 'RECOMMENDATION')),
    prompt TEXT NOT NULL,
    response TEXT,
    model_name VARCHAR(100),
    input_tokens INTEGER,
    output_tokens INTEGER,
    latency_ms BIGINT,
    rating INTEGER,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_ai_interactions_user_id FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ai_interactions_course_id FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_ai_interactions_topic_id FOREIGN KEY (topic_id) REFERENCES topics (id)
);

CREATE INDEX idx_ai_interactions_user_id ON ai_interactions (user_id);
CREATE INDEX idx_ai_interactions_course_id ON ai_interactions (course_id);
CREATE INDEX idx_ai_interactions_topic_id ON ai_interactions (topic_id);

-- Uploaded course material that the RAG service ingests.
CREATE TABLE documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL,
    topic_id BIGINT,
    uploaded_by_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(100),
    file_size BIGINT,
    storage_path VARCHAR(1000) NOT NULL,
    processed BOOLEAN NOT NULL DEFAULT FALSE,
    chunk_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_documents_course_id FOREIGN KEY (course_id) REFERENCES courses (id),
    CONSTRAINT fk_documents_topic_id FOREIGN KEY (topic_id) REFERENCES topics (id),
    CONSTRAINT fk_documents_uploaded_by_id FOREIGN KEY (uploaded_by_id) REFERENCES users (id)
);

CREATE INDEX idx_documents_course_id ON documents (course_id);
CREATE INDEX idx_documents_topic_id ON documents (topic_id);
CREATE INDEX idx_documents_uploaded_by_id ON documents (uploaded_by_id);

-- A text chunk of a document; embeddingId references the vector stored by the RAG service.
CREATE TABLE document_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL,
    chunk_index INTEGER NOT NULL DEFAULT 0,
    content TEXT NOT NULL,
    token_count INTEGER,
    page_number INTEGER,
    embedding_id VARCHAR(100),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_document_chunks UNIQUE (document_id, chunk_index),
    CONSTRAINT fk_document_chunks_document_id FOREIGN KEY (document_id) REFERENCES documents (id)
);

CREATE INDEX idx_document_chunks_document_id ON document_chunks (document_id);
